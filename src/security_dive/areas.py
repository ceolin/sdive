"""Areas generated from a project's own ownership file (Zephyr's MAINTAINERS.yml).

`sdive areas <p> --generate` reads the file at a snapshot commit and writes
`projects/<p>/<areas_source.file>`: one area per MAINTAINERS entry, its
`files` globs translated to sdive's glob syntax (a trailing `/` becomes
`/**`), with `files-exclude`, `files-regex` and `files-regex-exclude` kept.
Priorities are not generated: `[[priority]]` rules in `project.toml` set them
by area name, so regenerating never loses hand decisions.
"""

from __future__ import annotations

import re
from datetime import UTC, datetime

import yaml

from . import repo
from .config import Config, Project


def slug(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return s or "area"


def _glob(pattern: str) -> str:
    """MAINTAINERS.yml glob → sdive glob. Both treat `*` and `?` as not
    crossing `/`; MAINTAINERS' trailing `/` means everything below."""
    return pattern + "**" if pattern.endswith("/") else pattern


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _toml_list(xs: list[str]) -> str:
    return "[" + ", ".join(_toml_str(x) for x in xs) + "]"


def from_maintainers(text: str) -> list[dict]:
    """One area dict per MAINTAINERS.yml entry, in file order."""
    data = yaml.safe_load(text) or {}
    out, seen = [], {}
    for title, entry in data.items():
        if not isinstance(entry, dict):
            continue
        name = slug(title)
        if name in seen:           # titles differing only in punctuation
            seen[name] += 1
            name = f"{name}-{seen[name]}"
        else:
            seen[name] = 1
        out.append({
            "name": name,
            "description": title + (f" ({entry['status']})" if entry.get("status") else ""),
            "globs": [_glob(g) for g in entry.get("files", []) or []],
            "exclude": [_glob(g) for g in entry.get("files-exclude", []) or []],
            "regexes": list(entry.get("files-regex", []) or []),
            "regex_exclude": list(entry.get("files-regex-exclude", []) or []),
        })
    return out


def render(project: Project, sha: str, source: str, areas: list[dict]) -> str:
    lines = [
        f"# Generated by `sdive areas {project.name} --generate` from {source} at",
        f"# {sha} ({datetime.now(UTC).date()}). Do not edit: change `[[priority]]`",
        "# rules or add hand-written `[[areas]]` (matched first) in project.toml.",
        "",
        f"source = {{ file = {_toml_str(source)}, sha = {_toml_str(sha)} }}",
    ]
    for a in areas:
        lines += ["", "[[areas]]", f"name = {_toml_str(a['name'])}",
                  f"description = {_toml_str(a['description'])}"]
        for key in ("globs", "exclude", "regexes", "regex_exclude"):
            if a[key]:
                lines.append(f"{key} = {_toml_list(a[key])}")
    return "\n".join(lines) + "\n"


def generate(cfg: Config, project: Project, sha: str, source: str = "MAINTAINERS.yml") -> str:
    """Write the project's generated areas file from `source` at `sha`."""
    if project.areas_source is None:
        raise repo.GitError(f"{project.name}: no [areas_source] in project.toml")
    text = repo.git("-C", cfg.mirror_path(project.name), "show", f"{sha}:{source}")
    areas = from_maintainers(text)
    project.areas_source.write_text(render(project, sha, source, areas))
    return str(project.areas_source)
